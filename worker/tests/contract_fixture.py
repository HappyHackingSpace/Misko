"""Writes the cross-language contract fixture used by the Go analysis tests.

    python -m tests.contract_fixture ../backend/internal/analysis/adapters/catalog/testdata/worker_mwm_swim.json

It renders a synthetic MWM swim (7 s at 25 fps in a 120 cm tank), runs the
worker pipeline and stores the trajectory the worker would upload, together
with the ground truth the Go test compares the engine's metrics and events
with. Regenerate it when the trajectory format or the algorithm changes.
"""

from __future__ import annotations

import json
import math
import sys
import tempfile
from pathlib import Path

from misko_worker import ALGORITHM_VERSION
from misko_worker.pipeline import analyze, trajectory_document
from tests import synthetic
from tests.synthetic import Scene, _homography, disc_mask, pixel_to_cm

RADIUS = 60.0
PARAMETERS = {"tank_diameter_cm": 120.0, "platform_diameter_cm": 10.0, "platform_x_cm": 30.0, "platform_y_cm": 30.0,
              "wall_annulus_width_cm": 12.0, "min_platform_dwell_s": 1.0, "max_sample_gap_s": 0.5}
# Tank-centred, x east and y north (up on screen), about 1.7 px/cm.
CM_TO_PX = _homography([(RADIUS, 0), (0, RADIUS), (-RADIUS, 0), (0, -RADIUS)], [(262, 120), (160, 20), (58, 124), (162, 224)])
DURATION_S = 7.0
# Along the wall at 54 cm from the centre, from 200 degrees to 120 degrees.
WALL_RADIUS, WALL_FROM, WALL_TO = 54.0, math.radians(200), math.radians(120)
PLATFORM = (30.0, 30.0)
DESCRIPTION = (
    "Synthetic MWM swim in a 120 cm tank (platform 10 cm at (30, 30), wall annulus 12 cm): "
    "0-2.5 s along the wall at r=54 cm from 200 to 120 degrees (south-west through west into the north-west quadrant), "
    "2.5-5.5 s straight from (-27, 46.765) to the platform centre (30, 30), entering the target (north-east) quadrant at x=0, "
    "5.5-7 s still on the platform. Generated by worker/tests/contract_fixture.py."
)


def swim(t: float) -> tuple[float, float, bool]:
    if t < 2.5:
        a = WALL_FROM + (WALL_TO - WALL_FROM) * t / 2.5
        return WALL_RADIUS * math.cos(a), WALL_RADIUS * math.sin(a), True
    sx, sy = WALL_RADIUS * math.cos(WALL_TO), WALL_RADIUS * math.sin(WALL_TO)
    f = min(1.0, (t - 2.5) / 3.0)
    return sx + (PLATFORM[0] - sx) * f, sy + (PLATFORM[1] - sy) * f, True


def main(destination: str) -> None:
    scene = Scene(CM_TO_PX, disc_mask(CM_TO_PX, RADIUS), surround_level=95.0)
    with tempfile.TemporaryDirectory() as scratch:
        source = Path(scratch) / "swim.mp4"
        truth = synthetic.render(source, synthetic.regular(DURATION_S), swim, scene=scene, floor_level=150, subject_level=105,
                                 radius_cm=3.5)
        job = synthetic.job(run_id="01a00000-0000-7000-8000-00000000f1f1", clip_end_us=int(DURATION_S * 1_000_000))
        job["run"]["parameters"] = dict(PARAMETERS)
        job["calibration"] = synthetic.calibration(transform=pixel_to_cm(CM_TO_PX), crop=(48, 10, 226, 226))
        analysis = analyze(source, job, Path(scratch) / "overlay.mp4")
        trajectory = json.loads(trajectory_document(job, analysis))
    fixture = {
        "description": DESCRIPTION,
        "algorithm": ALGORITHM_VERSION,
        "paradigm": {"key": job["run"]["paradigmKey"], "version": job["run"]["paradigmVersion"]},
        "parameters": job["run"]["parameters"],
        "truth": {"tUs": [t.t_us for t in truth], "xCm": [round(t.x, 6) for t in truth], "yCm": [round(t.y, 6) for t in truth]},
        "trajectory": trajectory,
    }
    Path(destination).write_text(json.dumps(fixture, separators=(",", ":")) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
